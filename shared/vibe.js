/**
 * Вибрация в конце промежутка и цветных таймеров — одна и та же сцена VIBRATOR_SCENE_STRONG_REMINDER
 * и при включённом, и при погасшем экране (как в версии 10 на погасшем экране).
 *
 * Страница и служба будильника пишут в память метку «когда вибрировали» (ключ 'vibT'). Кто пришёл вторым и увидел
 * свежую метку — молчит: иначе при включённом экране сработали бы оба, а при погасшем — служба и потом страница,
 * открытая будильником.
 */
export const VIB_DEDUPE = 6000     // метка 'vibT' моложе этого (мс) — вибрация уже была
export const VIB_KEY = 'vibT'

/** Вибрировали ли только что (last — метка из памяти, now — сейчас). */
export function recentlyVibrated(last, now) {
  const l = +last || 0
  return l > 0 && now - l >= 0 && now - l < VIB_DEDUPE
}
